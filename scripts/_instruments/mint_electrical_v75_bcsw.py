def _canon(o):
    return json.dumps(o, sort_keys=True, separators=(",", ":"), default=str)


def _dump(p):
    return json.dumps(p, indent=1, ensure_ascii=False) + "\n"


def _connect(site):
    os.chdir("/workspace/development/frappe-bench/sites")
    import frappe
    frappe.init(site=site)
    frappe.connect()
    return frappe


def edits():
    return json.load(open(EDITS, encoding="utf-8"))


def _find(cfg, pid, match, where):
    """THE one step of `pid` whose keys equal `match` (all keys); anything else refuses by name."""
    steps = cfg["pipelines"][pid]["steps"]
    hits = [s for s in steps if all(s.get(k) == v for k, v in match.items())]
    if len(hits) != 1:
        raise SystemExit("%s: %d steps match %r in %s/%s (want exactly 1)" % (where, len(hits), match, cfg["category_id"], pid))
    return hits[0]


def apply_edits(prev, e=None):
    """v74 + the edits file's texts (price steps, bands, the carried installation cost steps, the remarks). Each entry's `old`
    must be the text it replaces (null = the step had none); a mismatch refuses."""
    e = e or edits()
    out = copy.deepcopy(prev)
    cfg = {c["category_id"]: c for c in out["category_configs"]}
    for group in ("price_steps", "stored_cost_steps"):
        for n, x in enumerate(e[group]):
            st = _find(cfg[x["category"]], x["pipeline"], x["match"], "%s[%d]" % (group, n))
            if st.get("explain") != x["old"]:
                raise SystemExit("%s[%d] %s/%s: today's line is %r, the edits file says %r" % (group, n, x["category"], x["pipeline"], st.get("explain"), x["old"]))
            st["explain"] = x["new"]
    for n, x in enumerate(e["band_explains"]):
        st = _find(cfg[x["category"]], x["pipeline"], x["match"], "band_explains[%d]" % n)
        bands = [b for b in st["bands"] if b.get("when") == x["when"]]
        if len(bands) != 1 or bands[0].get("explain") != x["old"]:
            raise SystemExit("band_explains[%d]: band %r not found once with the old text %r" % (n, x["when"], x["old"]))
        bands[0]["explain"] = x["new"]
    pis = {i["attributes"]["item"]: i for i in out["items"] if i["kind"] == PI_KIND}
    for item, text in e["remarks"].items():
        if item not in pis:
            raise SystemExit("remarks: no Electrical Pricing Input %r" % item)
        pis[item]["attributes"]["remarks"] = text
    return out


def strip_text(asset):
    """The asset with every TEXT field emptied: step / band `explain` and Pricing Input `remarks`. Two files equal after this
    differ in texts only."""
    a = copy.deepcopy(asset)
    for c in a["category_configs"]:
        for p in (c.get("pipelines") or {}).values():
            for s in p.get("steps") or []:
                for k in TEXT_KEYS:
                    s.pop(k, None)
                for b in s.get("bands") or []:
                    b.pop("explain", None)
    for i in a["items"]:
        if i["kind"] == PI_KIND:
            i["attributes"].pop("remarks", None)
    return a


def text_only(prev, final):
    """(changed texts table, ok): every difference between the two files is a text field; the table lists each one."""
    ok = _canon(strip_text(prev)) == _canon(strip_text(final))
    rows = []
    pc = {c["category_id"]: c for c in prev["category_configs"]}
    for c in final["category_configs"]:
        for pid, p in (c.get("pipelines") or {}).items():
            q = (pc[c["category_id"]].get("pipelines") or {}).get(pid) or {"steps": []}
            for n, (s, t) in enumerate(zip(q.get("steps") or [], p.get("steps") or [])):
                if s.get("explain") != t.get("explain"):
                    rows.append(["step", c["category_id"], pid, n, s.get("step"), s.get("explain"), t.get("explain")])
                for bs, bt in zip(s.get("bands") or [], t.get("bands") or []):
                    if bs.get("explain") != bt.get("explain"):
                        rows.append(["band", c["category_id"], pid, n, bs.get("when"), bs.get("explain"), bt.get("explain")])
    pi = {i["item_uid"]: i for i in prev["items"]}
    for i in final["items"]:
        if i["kind"] == PI_KIND and pi[i["item_uid"]]["attributes"].get("remarks") != i["attributes"].get("remarks"):
            rows.append(["remark", "pricing_inputs", i["attributes"]["item"], "", "", pi[i["item_uid"]]["attributes"].get("remarks"), i["attributes"].get("remarks")])
    return rows, ok


def build(out, site, table=None):
    frappe = _connect(site)
    from nirmaan_stack.services.boq_rate_master import config_validation
    from nirmaan_stack.services.boq_rate_master.loader import _validate_items, _validate_one_config
    raw = open(V74, "rb").read()
    prev = json.loads(raw.decode("utf-8"))
    if _dump(prev).encode("utf-8") != raw:
        raise SystemExit("re-dumping v74 does not reproduce its bytes")
    edited = apply_edits(prev)
    final = bcs_derive.apply(edited, stored=edited)
    assert bcs_derive.drift(final) == [], "the generated file does not regenerate to itself"
    rows, ok = text_only(prev, final)
    if not ok:
        raise SystemExit("v75 differs from v74 in something other than a text field")
    assert [k for k in final] == [k for k in prev]
    print("TEXT ONLY: every item, rate, step (but its line), input figure, config key and worked example byte-equal to v74; %d texts changed" % len(rows))
    for kind in ("step", "band", "remark"):
        print("   %-6s %d" % (kind, sum(1 for r in rows if r[0] == kind)))
    if table:
        with open(table, "w", encoding="utf-8") as fh:
            fh.write("what\tcategory\tpipeline / input\tstep\tstep kind / band\tv74\tv75\n")
            for r in rows:
                fh.write("\t".join(str(x if x is not None else "") .replace("\t", " ").replace("\n", " ") for x in r) + "\n")
        print("text table:", table)
    _validate_items(final["items"])
    stored = [dict(c, discipline=final["discipline"]) for c in final["category_configs"]]
    for n, c in enumerate(stored):
        c["goldens"] = final["goldens"].get(c["category_id"], c.get("goldens"))
        _validate_one_config(c, "category_configs[%d]" % n)
        config_validation._validate_config(c)
    rates = {(i["kind"], i["attributes"]["item"]): i["rates"] for i in final["items"] if str(i["kind"]).endswith("_pricing_input")}
    problems = config_validation.bcs_problems(stored, rates)
    if problems:
        raise SystemExit("bcs check refuses: %r" % problems)
    text = _dump(final)
    tokens = sorted(set(re.findall(r"v\d+", text)) - set(re.findall(r"v\d+", raw.decode("utf-8"))))
    if tokens:
        raise SystemExit("the asset text carries version-like tokens v74 does not %r (h07)" % tokens)
    open(out, "w", encoding="utf-8", newline="").write(text)
    print("candidate written:", out, "| items", len(final["items"]), "| configs", len(final["category_configs"]),
          "| sha256", hashlib.sha256(text.encode("utf-8")).hexdigest())
    frappe.destroy()


def run_agree(candidate, site, rows_file=None):
    prev = json.load(open(V74, encoding="utf-8"))
    final = json.load(open(candidate, encoding="utf-8"))
    rows, ok = text_only(prev, final)
    if not ok:
        raise SystemExit("the candidate differs from v74 in something other than a text field")
    diffs, n, counts = v74mint.exact_guard(prev, final, rows_file)
    print("EXACT GUARD v74 -> candidate: %d cases (agreement cases + worked examples%s), %d differ" % (n, " + rows of " + rows_file if rows_file else "", len(diffs)))
    for cid in sorted(counts):
        print("   %-18s %s" % (cid, counts[cid]))
    for d in diffs[:15]:
        print("   DIFF", d)
    if diffs:
        raise SystemExit("the mint refuses: a generated cost is not exactly v74's cost")


def load(candidate, site, rows_file=None):
    run_agree(candidate, site, rows_file)
    frappe = _connect(site)
    frappe.set_user("Administrator")
    from nirmaan_stack.services.boq_rate_master import exporter, loader
    payload = exporter.build_asset("Electrical")
    snap = exporter.write_snapshot("Electrical", exporter.serialize_asset(payload), payload)
    frappe.db.commit()
    print("PRE-LOAD SNAPSHOT", snap, "| items", len(payload["items"]), "| configs", len(payload["category_configs"]))
    s = loader.load_rate_master(path=candidate, replace=True)
    frappe.db.commit()
    print("LOAD SUMMARY:", json.dumps(s, default=str)[:1500])
    frappe.destroy()


